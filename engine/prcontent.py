"""The exact pull-request content a human authorizes: repo, branches, title, body and file hashes."""
from __future__ import annotations

import hashlib
import re
from typing import Optional

from . import common as c


def pr_body(state: dict, files: dict) -> str:
    """Deterministic PR body built only from approved artifacts, so a human can review it exactly."""
    ph = state["phases"]
    req_text = c.path(ph["requirements"]["artifact"]).read_text(encoding="utf-8")
    req_ids = sorted(set(re.findall(r"\bREQ-\d+\b", req_text)), key=lambda r: int(r.split("-")[1]))
    lines = ["## Summary", ph["implementation"]["summary"], "",
             "## Requirements covered", ", ".join(req_ids) or "none identified", "",
             "## Verification", "Verdict: PASS (verify artifact sha256 %s)" % ph["verify"]["artifact_sha256"][:12], "",
             "## Files"]
    lines += ["- `%s` (sha256 %s)" % (path, digest[:12]) for path, digest in sorted(files.items())]
    lines += ["", "Generated by the Agentic SDLC pipeline (run %s). Every phase was approved by a human." % state["run_id"]]
    return "\n".join(lines)


def build(state: dict, repo: str, head: str, base: str, title: Optional[str]) -> dict:
    """Compute the content record to authorize. Refuses if the working tree differs from the approved implementation."""
    files = dict(state["phases"]["implementation"].get("files") or {})
    if not files:
        raise c.SdlcError("the approved implementation recorded no files to publish")
    for rel, digest in files.items():
        fp = c.path(rel)
        if not fp.is_file() or c.sha256_file(fp) != digest:
            raise c.SdlcError("%s differs from the approved implementation (changed or deleted since approval); "
                              "reopen implementation" % rel)
    title = (title or "docs: synchronize documentation (%s)" % state["run_id"]).strip()
    if not title or len(title) > 120 or "\n" in title:
        raise c.SdlcError("--title must be one line of 1-120 characters")
    body = pr_body(state, files)
    content_digest = hashlib.sha256(c.canonical([repo, head, base, title, body, files]).encode("utf-8")).hexdigest()
    return {"repo": repo, "head": head, "base": base, "title": title, "body": body,
            "body_sha256": hashlib.sha256(body.encode("utf-8")).hexdigest(), "files": files,
            "content_digest": content_digest}
